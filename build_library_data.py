def load_std():
    p = os.path.join(SRC, "std_clean.json")
    if not os.path.exists(p):
        p = "/tmp/std_clean.json"
    if not os.path.exists(p):
        print("缺少 std_clean.json，请先运行清洗脚本")
        sys.exit(1)
    return json.load(open(p, encoding="utf-8"))

