#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""案例库闸门：把「不是处罚案例」的条目挡在页面之外。

背景（2026-09-17 用户反馈）
-------------------------
案例库上线后表格里混进了大量**执法新闻**：会议、座谈会、推进会、年度报告、
白皮书、政策出台、约谈、统一销毁行动、工作部署、「铁腕治劣 取得成效」这类
工作总结。它们都来自「市场监管总局要闻」这类**新闻栏目**，正文里一个被处罚
主体都没有，却因为标题含「执法 / 案例 / 处罚」被 HIT 正则放过。

处理原则
--------
**不删数据，只打标**：命中闸门的记录在 cases.json 里保留原样，只加
`noncase: true` + `noncase_reason`，由 `build_cases_page.py` 在构建时过滤。
原始记录是溯源凭据，删掉就再也说不清「这条为什么没上页面」。

判据分三层
----------
A **会议类（无条件剔除）**：召开 / 开幕 / 座谈 / 研讨 / 推进会 / 论坛 / 交流大会
   ——即便正文里列了案例（「某大会发布十大案例」），它本身也不是一条处罚，
      而是一个发布行为；这类内容应作为「资讯」进资讯流，不进案例库。
B **非处罚执法内容**：约谈（行政指导，不是处罚）、年度报告 / 白皮书 / 成效统计、
   政策出台 / 征求意见稿、评选活动 / 工作部署、集中销毁行动、监管创新案例。
C **误伤保护**：标题里同时出现「典型案例 / 案例 / 通报一批 / 曝光」且不含 A/B 词的，
   **保留** —— 那是「XX 公布一批铁拳行动典型案例」这类案例汇编，是案例库的主力内容。

⚠️ 踩过的坑：**不能用「品牌」做关键词**。它是「XX 品牌管理有限公司实施混淆行为案」
（泸州，真案例）的子串，一刀切会把真案例剔掉。要写就写 `打造.{0,8}品牌`。
"""
import re

# ── A 会议类（无条件剔除，不受 C 层保护影响）──────────────
_A_MEETING = re.compile(
    r"召开|开幕|闭幕|举行|座谈|研讨|推进会|现场会|论坛|交流大会|"
    r"培训班|宣讲会|行政指导会|工作会|发布会"
)
# ── B 非处罚执法内容 ────────────────────────────────────
_B_OTHER = re.compile(
    # 约谈 —— 行政指导/告诫，不产生处罚决定
    r"约谈|问询|告诫|"
    # 报告 / 统计 / 总结
    r"年度报告|白皮书|发展报告|执法报告|工作报告|专项治理报告|"
    r"取得成效|成效显著|综述|盘点|回顾|纪实|侧记|工作纪实|"
    r"办结案件|查处[^，。]{0,12}\d+\s*(?:余)?件|立案[^，。]{0,12}\d+\s*(?:余)?件|"
    # 解读 / 科普
    r"解读|答记者问|一图读懂|图解|专访|访谈|科普|"
    # 政策 / 立法
    r"征求意见|草案|印发|出台|修订|立法|行动方案|"
    # 部署 / 活动 / 评选
    r"评选活动|评选结果|揭晓|启动仪式|部署开展|部署|专项行动工作|专项整治工作|"
    r"统一销毁行动|集中统一销毁|销毁侵权假冒|集中销毁|"
    r"监管创新案例|创新案例|"
    # 专项行动 / 整治动态（工作推进，不是个案）
    r"开展[^，。]{0,20}(?:统一)?(?:执法|整治|专项)[^，。]{0,6}行动|"
    r"推进[^，。]{0,10}行动|深化[^，。]{0,10}整治|专项治理|"
    r"严查[^，。]{0,12}(?:领域|行为)|重点打击|重拳打击|打击整治|"
    # ⚠️ 「乱象」两端常被空格/换行断开（「…"铁拳"整治 民生领域乱象」），
    #    不能写成紧邻的 `整治乱象`。
    r"整治[^，。]{0,12}乱象|"
    r"严打[\d一二三四五六七八九十]+种|震慑力|"
    # 口号式宣传稿：无案号、无主体，只有「保安全 / 护民生 / 强化执法」这类标语
    r"强化执法|保安全|护民生|"
    # 「品牌」不能单独用（会命中「XX 品牌管理有限公司…案」真案例），
    # 必须锚定在「打造…品牌」这种宣传语境里，且允许中间夹引号与空格。
    r"打造[^，。]{0,16}品牌|"
    # 提醒 / 宣传
    r"提醒[^，。]{0,24}意识|"
    # 「XX：严查/重点打击…」这种标题冒号式工作部署
    r"^[^，。]{0,20}[:：][^，。]{0,30}(?:违法行为|乱象)$|"
    # 程序性公告（专项治理公告、督促整改通知），本身不含处罚决定
    r"专项治理的?公告|专项治理的?通告|督促[^，。]{0,20}尽快整改的通知"
)
# ── 案例汇编保护词 ────────────────────────────────────
_C_CASEBOOK = re.compile(r"典型案例|案例|通报|曝光|处罚|查处|罚款|案\b")
# ── D 标题含「铁拳/春雷」等行动名、却通篇没有案例的 → 工作动态 ──
_ACTION_NAME = re.compile(r"铁拳|春雷|守护消费|打假清源|执法亮剑")
_HAS_CASE = re.compile(r"典型案例|案例|案件|案（|案\(|处罚|查处|曝光台")

# 例外白名单：标题含这些词的一律保留（人工确认过的真案例）
_KEEP = re.compile(r"处罚决定书|行政处罚决定|行政处罚信息公开")

# ── E 非行政处罚（行政裁决）──────────────────────────────
# 「专利侵权纠纷行政裁决」是**维权裁决**（判断是否侵权、责令停止），不是行政处罚：
# 无罚款、无被处罚主体、标题只有专利号。佛山站一页 41 条 fact 全是同一句模板
# （「被请求人未经专利权人许可…」），信息密度极低且大量重复 —— 不计入处罚案例。
_NON_PENALTY_KIND = re.compile(r"专利侵权纠纷行政裁决|行政裁决")
# ⚠️ 光按 kind 判会漏：佛山同一个页面被两种 kind 处理过，有一批记录的 kind
# 被标成「行政处罚信息公开表」，标题却是「专利号为 ZL…的外观设计专利纠纷」。
# 所以标题也要判 —— 含「专利」且含「纠纷」即为裁决类。
_NON_PENALTY_TITLE = re.compile(r"专利.{0,40}纠纷|专利权.{0,20}纠纷")


def classify(title, fact="", kind=""):
    """返回 (keep: bool, reason: str)。

    reason 只在 keep=False 时有值，写进记录的 `noncase_reason`，
    便于日后复核「这条为什么被挡」。
    """
    t = (title or "").strip()
    if not t:
        return False, "空标题"
    if _NON_PENALTY_KIND.search(kind or "") or _NON_PENALTY_TITLE.search(t):
        return False, "非行政处罚（行政裁决）"
    if _KEEP.search(t):
        return True, ""
    if _A_MEETING.search(t):
        return False, "会议/发布活动"
    if _ACTION_NAME.search(t) and not _HAS_CASE.search(t):
        return False, "专项行动工作动态"
    if _B_OTHER.search(t):
        # C 层保护：案例汇编（「XX 公布一批…典型案例」）不因 B 词被误杀
        if _C_CASEBOOK.search(t) and re.search(r"公布|发布|通报|曝光|公布一批|公布十?[一二三四五六七八九十\d]+起", t):
            return True, ""
        return False, "执法工作动态/报告/政策"
    return True, ""
