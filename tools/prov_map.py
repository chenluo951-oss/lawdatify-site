def is_national(title="", url=""):
    """这条内容是否属于「全国性发布」。"""
    t = title or ""
    for k in NATIONAL_TITLE_KW:
        if k in t:
            return True
    try:
        from urllib.parse import urlparse
        h = (urlparse(url or "").netloc or "").lower()
        for nat in NATIONAL_HOSTS:
            if h == nat or h.endswith("." + nat):
                return True
    except Exception:
        pass
    return False


def detect_issuer(agency="", org="", title="", body="", url=""):
    """属地判定唯一入口：多证据计分，达到 GEO_MIN 采纳。

    返回 (省名, 依据) 或 (None, "")。依据形如 "agency" / "title+host+body"。

    为什么不用「先命中先返回」：单一判据都不够 ——
      · **只看域名**：地方站转发全国性内容会被误归该省（用户 2026-09-17 指出）；
      · **只看正文**：总局合集里提到某省案例会被误归该省；
      · **只看标题**：「第二届知识产权执法国际交流大会在长沙开幕」会被误归湖南。
    所以改为计分：发布机关/机构 > 标题 > 正文（单省才计）> 域名，跨过阈值才采纳。

    正文计分的两条护栏（2026-09-17 实测）：
      ① 正文出现 **≥3 个不同省份** → 全国合集，正文不计分；
      ② `is_national()` 为真（标题含全国机关名，或链接挂在部委域名下）
         → 正文与域名都不计分。
    """
    sc = {}
    why = {}
    national = is_national(title, url)

    def add(prov, w, tag):
        if not prov or w <= 0:
            return
        sc[prov] = sc.get(prov, 0) + w
        why.setdefault(prov, []).append(tag)

    add(_plain(agency), W_AGENCY, "agency")
    add(_plain(org), W_ORG, "org")
    head = _plain(title, limit=16)
    add(head, W_TITLE_HEAD, "title")
    add(agency_in_text(title), W_TITLE_KW, "title-kw")
    if not head:
        add(_plain(title), W_TITLE, "title")

    if not national:
        bp = body_provs(body)
        if len(bp) == 1:
            add(next(iter(bp)), W_BODY, "body")
        elif len(bp) == 2:
            for p in bp:
                add(p, 1, "body?")
        # ≥3 省：全国性合集，正文不计分
        try:
            from urllib.parse import urlparse
            add(prov_of_host(urlparse(url or "").netloc), W_HOST, "host")
        except Exception:
            pass

    if not sc:
        return None, ""
    prov = max(sc.items(), key=lambda kv: (kv[1], -len(kv[0])))[0]
    if sc[prov] < GEO_MIN:
        return None, ""
    return prov, "+".join(why.get(prov, []))


