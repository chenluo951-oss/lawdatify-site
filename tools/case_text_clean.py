# -*- coding: utf-8 -*-
"""案例正文的「页面壳」清洗（harvest_cases / harvest_local_amr 共用）。

## 为什么需要

政府站详情页的正文区外面裹着一圈**站内导航与元信息栏**，`textify()` 之后会混进
案例摘要里，典型长这样：

    上海曝光违规改装电动自行车典型案例 你的位置: 首页 > 专题 > “铁拳”行动 曝光台
    上海曝光违规改装电动自行车典型案例 发布时间：2025-06-23 15:33 信息来源：市场监管总局
    市场监管部门针对电动自行车……（真正的正文）

三块噪声，一块比一块隐蔽：

1. **面包屑**（`你的位置: 首页 > …`）—— 没有句读、没有空格边界，只能靠
   「元信息标签」当前锚点来截断；
2. **元信息栏**（`发布时间：2026-06-11 17:00` / `信息来源：市场监管总局`）；
3. **PDF 页码残留**（`第67页,共1715页`）—— 站内原文库有条目源自 PDF 拼接。

## ⚠️ 踩过的坑（别退回去）

老写法用 `re.sub(r"来源：.{0,40}", " ")` 删「来源」，`.{0,40}` 是**贪婪且不限字符**的，
把「来源：市场监管总局 市场监管部门针对电动自行车生产、销售领域违法违」整段吃掉了
—— 376 条记录因此各丢了几十个正文字。**元信息的「值」必须限长，且要卡在词边界上**。
"""

import re

# 面包屑：从「你的位置」一路到下一个元信息标签/正文起点
_CRUMB = re.compile(
    r"(?:你的位置|您现在的位置|您的位置|当前位置|当前所在位置|您现在所在的位置)"
    r"\s*[:：][^\n]{0,200}?"
    r"(?=发布\s*(?:时间|日期)|信息\s*(?:来源|索引|发布)|索引号|文号|来源\s*[:：]|成文日期|$)"
)

# 元信息标签 + **限长的值**：值要么是日期时间，要么是不含空格且 ≤16 字的短串
_DT = (r"\d{4}\s*[-/年]\s*\d{1,2}\s*[-/月]\s*\d{1,2}\s*日?"
       r"(?:\s*\d{1,2}\s*:\s*\d{2}(?:\s*:\s*\d{2})?)?")
_META = re.compile(
    r"(?:发布\s*(?:时间|日期)|信息\s*(?:来源|发布)|来源|索引号|成文日期|生成日期|公开日期|"
    r"公开方式|公开时限|发文机关|发文字号|文号|主题分类|体裁分类|组配分类|有效性|"
    r"效力状态|服务对象|浏览次数|浏览\s*量|关键词)\s*[:：]\s*"
    r"(?:" + _DT + r"|[^\s]{0,16}(?=\s|$))"
)

# 页面功能件
_UI = re.compile(
    r"(?:打印本页|打印页面|关闭窗口|关闭本页|分享到|扫一扫在手机上?查看|"
    r"字体\s*[:：]?\s*[大小中]{1,2}|附件下载|上一篇|下一篇|返回列表|返回顶部)"
)

# PDF 页码 / 分页残留
_PDFNO = re.compile(r"第\s*\d+\s*页\s*[,，]?\s*共\s*\d+\s*页")

# 只有标签没有值的尾巴（清洗后可能留下孤零零的「信息来源：」）
_ORPHAN = re.compile(
    r"(?:你的位置|您现在的位置|您的位置|当前位置|发布\s*(?:时间|日期)|信息\s*(?:来源|发布)|"
    r"来源|索引号|成文日期|公开日期|浏览次数)\s*[:：]\s*$"
)


def _cut_nonspace(t, n):
    """丢掉前 n 个**非空白**字符（正文坐标以扁平串计，原串里的空白不算数）。"""
    cnt = 0
    for i, ch in enumerate(t):
        if not ch.isspace():
            if cnt == n:
                return t[i:].lstrip()
            cnt += 1
    return ""


def clean_fact(s, title=""):
    """剥掉面包屑 / 元信息栏 / 页面功能件，返回干净正文。

    title 传入时额外做一件事：**去掉重复出现的标题**——政府站普遍是
    `<h1>标题</h1> → 面包屑 → 标题 → 发布信息 → 正文`，正文开头的标题重复
    在摘要里就是纯噪声。
    """
    t = re.sub(r"\s+", " ", s or "").strip()
    if not t:
        return ""

    t = _PDFNO.sub(" ", t)
    t = _UI.sub(" ", t)
    t = _CRUMB.sub(" ", t)
    t = _META.sub(" ", t)
    t = _ORPHAN.sub(" ", t)
    t = re.sub(r"\s+", " ", t).strip()

    # 正文起点：优先取**最后一次**出现标题的位置（第一次是页面大标题）
    if title:
        key = re.sub(r"\s+", "", title)
        if len(key) >= 8:
            flat = re.sub(r"\s+", "", t)
            pos = flat.rfind(key[:12])
            if pos > 0:
                t = _cut_nonspace(t, pos)
            # 剥掉开头的标题本身（面包屑被清掉后，标题常只剩这一处，
            # 但它在摘要里同样是噪声）
            flat = re.sub(r"\s+", "", t)
            if flat.startswith(key[:12]):
                t = _cut_nonspace(t, len(key))
    # 清掉残留的孤立标签与前导标点
    t = re.sub(r"^[\s:：,，、;；>＞\-—·]+", "", t)
    t = _META.sub(" ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def is_shell(s):
    """还残留页面壳吗？（用于批量体检 / 决定是否重取）"""
    return bool(re.search(
        r"你的位置|您现在的位置|当前位置\s*[:：]|发布时间\s*[:：]|信息来源\s*[:：]|"
        r"第\s*\d+\s*页\s*[,，]?\s*共\s*\d+\s*页",
        s or ""))


