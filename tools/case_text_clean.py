# -*- coding: utf-8 -*-
"""案例正文的「页面壳」清洗（harvest_cases / harvest_local_amr 共用）。

## 为什么需要

政府站详情页的正文区外面裹着一圈**站内导航与元信息栏**，`textify()` 之后会混进
案例摘要里，典型长这样：

    上海曝光违规改装电动自行车典型案例 你的位置: 首页 > 专题 > “铁拳”行动 曝光台
    上海曝光违规改装电动自行车典型案例 发布时间：2025-06-23 15:33 信息来源：市场监管总局
    市场监管部门针对电动自行车……（真正的正文）

三块噪声，一块比一块隐蔽：

1. **面包屑**（`你的位置: 首页 > …`）—— 没有句读、没有空格边界，只能靠
   「元信息标签」当前锚点来截断；
2. **元信息栏**（`发布时间：2026-06-11 17:00` / `信息来源：市场监管总局`）；
3. **PDF 页码残留**（`第67页,共1715页`）—— 站内原文库有条目源自 PDF 拼接。

## ⚠️ 踩过的坑（别退回去）

老写法用 `re.sub(r"来源：.{0,40}", " ")` 删「来源」，`.{0,40}` 是**贪婪且不限字符**的，
把「来源：市场监管总局 市场监管部门针对电动自行车生产、销售领域违法违」整段吃掉了
—— 376 条记录因此各丢了几十个正文字。**元信息的「值」必须限长，且要卡在词边界上**。
"""

import re

# 面包屑：从「你的位置」一路到下一个元信息标签/正文起点
# ⚠️ 中间段必须**卡在句末标点之前**（`[^。\n]{0,120}?`）：早先写成 `[^\n]{0,200}?`，
# 面包屑后面若隔了半句正文才出现「信息来源」，会连正文一起吃（实测「全国25个省」
# 被吃成「国25个省」）。面包屑不可能跨句号。
_CRUMB = re.compile(
    r"(?:你的位置|您现在的位置|您的位置|当前位置|当前所在位置|您现在所在的位置)"
    r"\s*[:：][^。\n]{0,120}?"
    r"(?=发布\s*(?:时间|日期)|信息\s*(?:来源|索引|发布)|索引号|文号|来源\s*[:：]|成文日期|$)"
)

# 元信息标签 + **限长的值**：值要么是日期时间，要么是不含空格且 ≤16 字的短串
_DT = (r"\d{4}\s*[-/年]\s*\d{1,2}\s*[-/月]\s*\d{1,2}\s*日?"
       r"(?:\s*\d{1,2}\s*:\s*\d{2}(?:\s*:\s*\d{2})?)?")
_META = re.compile(
    r"(?:发布\s*(?:时间|日期)|信息\s*(?:来源|发布)|来源|索引号|成文日期|生成日期|公开日期|"
    r"公开方式|公开时限|发文机关|发文字号|文号|主题分类|体裁分类|组配分类|有效性|"
    r"效力状态|服务对象|浏览次数|浏览\s*量|关键词)\s*[:：]\s*"
    r"(?:" + _DT + r"|[^\s]{0,16}(?=\s|$))"
)

# 页面功能件
_UI = re.compile(
    r"(?:打印本页|打印页面|关闭窗口|关闭本页|分享到|扫一扫在手机上?查看|"
    r"字体\s*[:：]?\s*[大小中]{1,2}|附件下载|上一篇|下一篇|返回列表|返回顶部|"
    # 字号切换控件：`【 中 小 】 -->`（总局站每页都有，176/699 条命中）
    r"【\s*[大中小]\s*[大中小]?\s*】|"
    # 表格展开控件的残留：`显示全部表格信息 start-->`
    r"显示全部表格信息|start\s*-{1,2}>|"
    # 纯箭头残留（需成对比较避免吃掉正文里的破折号：要求前后无汉字紧邻数字等）
    r"(?<![\u4e00-\u9fa5])-{2}\s*>(?![\u4e00-\u9fa5]))"
)

# 附件区：附件名（`.docx` 等）与「附件：」列表。政府站正文区下方挂一片附件，
# textify() 之后就是「.docx 青岛市…告知书(青黄市监罚告〔2026〕4437-4461号).docx
# 附件：拟吊销营业执照的企业名单.xls」这种串（143/699 条命中）。
_ATTACH = re.compile(
    r"(?:[\u4e00-\u9fa5A-Za-z0-9（）()《》〔〕\[\]【】_\-—·．.、]*)"
    r"\.(?:docx?|xlsx?|pdf|zip|rar|wps|et|ppt|pptx|ofd)\s*|"
    r"(?:附件|相关链接|下载附件|相关附件|附件下载)\s*[:：][^。]{0,120}"
)

# 页脚：网站标识码、备案号、主办单位一类的固定件
_FOOT = re.compile(
    r"政府网站标识码\s*[:：]?\s*\d+|"
    r"[\u4e00-\u9fa5]{1,2}ICP备\s*\d+\s*号?(?:-\d+)?|"
    r"(?:京|沪|粤|浙|苏|鲁|皖|赣|湘|鄂|川|渝|云|贵|闽|桂|冀|豫|晋|陕|甘|青|宁|新|辽|吉|黑|津)公网安备\s*\d+\s*号?|"
    r"网站地图|联系我们|主办(?:单位)?\s*[:：]|承办(?:单位)?\s*[:：]|"
    r"版权所有|技术支持\s*[:：]|网站标识码|"
    # 青岛等地市站的页脚三连：`©青岛市市场监督管理局 地址：… 联系电话：…`
    r"©\s*[\u4e00-\u9fa5]{0,20}(?:版权)?(?:所有)?|"
    r"(?:地\s*址|联系电话|电\s*话|邮\s*编|传真)\s*[:：]\s*[^\s]{0,40}"
)

# PDF 页码 / 分页残留
_PDFNO = re.compile(r"第\s*\d+\s*页\s*[,，]?\s*共\s*\d+\s*页")

# 只有标签没有值的尾巴（清洗后可能留下孤零零的「信息来源：」）
_ORPHAN = re.compile(
    r"(?:你的位置|您现在的位置|您的位置|当前位置|发布\s*(?:时间|日期)|信息\s*(?:来源|发布)|"
    r"来源|索引号|成文日期|公开日期|浏览次数)\s*[:：]\s*$"
)


def _cut_nonspace(t, n):
    """丢掉前 n 个**非空白**字符（正文坐标以扁平串计，原串里的空白不算数）。"""
    cnt = 0
    for i, ch in enumerate(t):
        if not ch.isspace():
            if cnt == n:
                return t[i:].lstrip()
            cnt += 1
    return ""


def clean_fact(s, title=""):
    """剥掉面包屑 / 元信息栏 / 页面功能件，返回干净正文。

    title 传入时额外做一件事：**去掉重复出现的标题**——政府站普遍是
    `<h1>标题</h1> → 面包屑 → 标题 → 发布信息 → 正文`，正文开头的标题重复
    在摘要里就是纯噪声。
    """
    t = re.sub(r"\s+", " ", s or "").strip()
    if not t:
        return ""

    t = _PDFNO.sub(" ", t)
    t = _UI.sub(" ", t)
    t = _CRUMB.sub(" ", t)
    t = _META.sub(" ", t)
    t = _ORPHAN.sub(" ", t)
    t = _ATTACH.sub(" ", t)
    t = _FOOT.sub(" ", t)
    t = re.sub(r"\s+", " ", t).strip()

    # 正文起点：优先取**最后一次**出现标题的位置（第一次是页面大标题）
    # ⚠️ 「剥掉开头标题」的判据是**原始串里标题出现过两次**（h1 一次 + 面包屑区一次，
    # 后者常被 _CRUMB 一并吃掉，所以剥完壳后数不出第二次）。不能只看剥壳后的结果：
    # 政府站有「标题恰好等于正文首句」的畸形记录（采集时误把正文首句当标题），
    # 那种记录里标题只出现一次，再剥一次就把正文吃掉了 —— 实测
    # 「当事人购进陈皮时未如实记录该批陈皮的名称、规格、数量、生产日」被削成
    # 「期、生产批号、保质期…」。
    if title:
        key = re.sub(r"\s+", "", title)
        if len(key) >= 8:
            raw = re.sub(r"\s+", "", s or "")
            dup = raw.count(key[:12]) >= 2
            flat = re.sub(r"\s+", "", t)
            pos = flat.rfind(key[:12])
            if pos > 0:
                t = _cut_nonspace(t, pos)
                flat = re.sub(r"\s+", "", t)
                if flat.startswith(key):
                    t = _cut_nonspace(t, len(key))
            elif dup and flat.startswith(key):
                t = _cut_nonspace(t, len(key))
    # 清掉残留的孤立标签与前导标点
    t = re.sub(r"^[\s:：,，、;；>＞\-—·]+", "", t)
    t = _META.sub(" ", t)
    t = re.sub(r"\s+", " ", t).strip()

    # 剥完只剩零星残渣（原串是一整片「附件名 + 页脚」）→ 当**没有正文**处理。
    # 「宁缺勿错」：案例库的「处罚事由」列宁可写「见原文」，也不能塞一段
    # 附件清单进去（`cs-note` 已说明该字段可能留空）。
    if len(t) < 30 and len(re.sub(r"\s+", "", s or "")) >= 60:
        return ""
    return t


def is_shell(s):
    """还残留页面壳吗？（用于批量体检 / 决定是否重取）"""
    return bool(re.search(
        r"你的位置|您现在的位置|当前位置\s*[:：]|发布时间\s*[:：]|信息来源\s*[:：]|"
        r"第\s*\d+\s*页\s*[,，]?\s*共\s*\d+\s*页",
        s or ""))


