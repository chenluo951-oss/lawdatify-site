def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    d = json.load(open(PATH, encoding="utf-8"))
    cats = d["categories"]
    have = {c["id"]: c for c in cats}

    added_cat, added_scene, added_duty = [], [], 0
    for c in NEW:
        if c["id"] in have:
            continue
        cats.append(c)
        added_cat.append(c["name"])
        added_scene += [s["name"] for s in c["scenes"]]
        added_duty += sum(len(s["duties"]) for s in c["scenes"])
    for cid, scenes in EXTEND.items():
        c = have.get(cid)
        if not c:
            continue
        existing = {s["name"] for s in c["scenes"]}
        for s in scenes:
            if s["name"] in existing:
                continue
            c["scenes"].append(s)
            added_scene.append("%s / %s" % (c["name"], s["name"]))
            added_duty += len(s["duties"])

    tot_cat = len(cats)
    tot_scene = sum(len(c["scenes"]) for c in cats)
    tot_duty = sum(len(s["duties"]) for c in cats for s in c["scenes"])
    print("新增类目 %d：%s" % (len(added_cat), "、".join(added_cat) or "无"))
    print("新增场景 %d：%s" % (len(added_scene), "、".join(added_scene) or "无"))
    print("新增义务 %d" % added_duty)
    print("合计：%d 大类 / %d 场景 / %d 项义务" % (tot_cat, tot_scene, tot_duty))
    if a.check:
        return
    d["_meta"]["updated"] = "2026-09-11"
    d["_meta"]["note"] += "；2026-09-11 扩写即时零售/前置仓/即时配送/网络餐饮与线下餐饮/零售会员/计量/绿色包装七个业务域。"
    open(PATH, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=1))
    print("已写入 %s" % os.path.relpath(PATH, ROOT))


if __name__ == "__main__":
    main()
