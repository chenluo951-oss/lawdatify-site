def main():
    d = json.load(open(P, encoding="utf-8"))
    cats = {c["id"]: c for c in d["categories"]}
    new_s = new_d = 0
    for cid, scenes in ADD.items():
        c = cats.get(cid)
        if not c:
            print(f"  ! 未找到主题大类 {cid}")
            continue
        idx = {s["name"]: s for s in c["scenes"]}
        for name, duties, desc in scenes:
            if name in idx:
                have = {x.get("t") for x in idx[name].get("duties", [])}
                fresh = [x for x in duties if x.get("t") not in have]
                if not fresh:
                    print(f"  · {cid}/{name} 义务已齐备，跳过")
                    continue
                idx[name].setdefault("duties", []).extend(fresh)
                new_d += len(fresh)
                print(f"  + {cid}/{name} 续写 {len(fresh)} 项")
            else:
                if not desc:
                    print(f"  ! {cid}/{name} 场景不存在且未给描述，跳过")
                    continue
                c["scenes"].append({"name": name, "duties": duties, "desc": desc})
                new_s += 1
                new_d += len(duties)
                print(f"  ★ {cid} / {name} 新建场景（{len(duties)} 项）")
    tot_s = sum(len(c["scenes"]) for c in d["categories"])
    tot_d = sum(len(s["duties"]) for c in d["categories"] for s in c["scenes"])
    d["_meta"]["updated"] = date.today().isoformat()
