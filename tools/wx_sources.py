def authority_tier(name):
    """按公众号账号名判定档位（国家 + 省市多级机关都认）。

    返回 "wechat-official" / "academic" / "research" / None（None=不在放行名单）。
    """
    a = (name or "").strip()
    if not a:
        return None
    for tier, rx in ACCOUNT_TIER_RULES:
        if rx.search(a):
            return tier
    return None


# ---------------------------------------------------------------- 检索词生成
#
# 设计原则（用户 2026-09-15：「为什么要收敛检索词数量？」）
# ----------------------------------------------------------------
# 覆盖的**单位是「机关账号」，不是「词 × 机关」的笛卡尔积**：
#   · 必达约束：REGIONS(87) × 八类主体 = 696 个机关账号位，**一个不漏**；
#   · 词维度**滚动深挖**：每个机关位从该类词表的滚动位置取 N 个词，
#     随机关序号前移，多轮下来词表被完整覆盖；
#   · 因此本池子「只增不减」——新增省份 / 城市 / 账号即自动进入池子，
#     不存在 `[:3]` 一类截断。
#
# 单日执行量由 sweep_wx.py 的**每日预算**调度决定（周期 = 总数 ÷ 日预算，
# 自动延长），所以来源层可以放心扩容，不需要为了迁就限流而砍来源。

# 每个机关账号位每次取用的检索词个数（滚动；可从环境变量调大以加深覆盖）
PER_ACCOUNT_TERMS = 4


def _roll(terms, i, n=None):
    """在词表上滚动取 n 个词。

    第 i 个机关位从第 (i*n) % len(terms) 个词开始连续取，
    保证：① 单轮内每个机关位都有 n 个检索词（不漏机关）；
    ② 机关序号前移时取词位置同步前移，多轮之后覆盖词表全部词（深挖）。
    """
    L = len(terms)
    if L == 0:
        return []
    n = min(n or PER_ACCOUNT_TERMS, L)
    k = (i * n) % L
    return [terms[(k + j) % L] for j in range(n)]


def build_queries():
    """生成全量检索词池：八类监管主体 ×（国家 + 31 省 + 重点城市）× 滚动全量合规词。

    **本函数不做截断式收敛**（用户 2026-09-15 明确要求）。
    单日执行量由 sweep_wx.py 的每日预算调度决定，与来源覆盖无关。

    检索词形如「网信浙江 个人信息保护」「市说新语 食品安全」。
    org 写进存档 JSON，页面渲染时即显示为发布机关，空串则交账号名推断。
    """
    q = []
    seen = set()

    def add(query, org):
        key = (query, org)
        if key in seen:
            return
        seen.add(key)
        q.append((query, org))

    # ============ 1) 网信办 ============
    for t in CAC_TERMS:                                   # 中央层：全量词
        add(f"网信中国 {t}", CENSUS_CAC)
    for i, p in enumerate(REGIONS):
        for t in _roll(CAC_TERMS, i):
            add(f"网信{p} {t}", f"{p}网信办")
        add(f"{p}网信办 个人信息", f"{p}网信办")           # 账号名变体

    # ============ 2) 公安 / 网安 ============
