def build_queries():
    """生成全量检索词池（约 300+ 条）：八类监管主体 × 国家/省/市 × 核心合规词。

    检索词形如「网信浙江 个人信息保护」「市说新语 食品安全」。
    org 写进存档 JSON，页面渲染时即显示为发布机关，空串则交账号名推断。
    """
    q = []
    seen = set()

    def add(query, org):
        key = (query, org)
        if key in seen:
            return
        seen.add(key)
        q.append((query, org))

    # 1) 网信办：中央
    for t in CAC_TERMS:
        add(f"网信中国 {t}", CENSUS_CAC)
    # 1) 网信办：省 + 重点城市（每省 3 个核心词，控总量）
    for p in PROVINCES + KEY_CITIES:
        for t in CAC_TERMS[:3]:
            add(f"网信{p} {t}", f"{p}网信办")

    # 2) 公安 / 网安：中央多账号
    for acct, org in [("公安部网安局", "公安部网络安全保卫局"),
                      ("国家网络安全通报中心", "国家网络安全通报中心"),
                      ("网安局", "公安部网络安全保卫局")]:
        for t in PSB_TERMS[:4]:
            add(f"{acct} {t}", org)
    # 2) 公安：重点省市网警 / 平安号
    for p in ["北京", "上海", "广东", "浙江", "江苏", "四川", "山东", "湖北",
              "福建", "深圳", "杭州", "南京", "成都", "武汉"]:
        add(f"{p}网警 网络安全", f"{p}公安网安")
        add(f"平安{p} 反诈", f"{p}公安")

    # 3) 市场监管：总局
    for t in SAMR_TERMS:
        add(f"市说新语 {t}", "市场监管总局")
    # 3) 市场监管：省 / 市局（每省 4 个核心词）
    for p in PROVINCES + KEY_CITIES:
        for t in SAMR_TERMS[:4]:
            add(f"{p}市场监管 {t}", f"{p}市场监管局")

    # 4) 工信 / 通管：工信部
    for t in MIIT_TERMS:
        add(f"工信微报 {t}", "工业和信息化部")
    # 4) 工信：省通管局
    for p in ["北京", "上海", "广东", "浙江", "江苏", "四川", "山东", "湖北",
              "福建", "河南", "河北", "湖南", "陕西", "辽宁", "深圳"]:
        add(f"{p}通信管理局 个人信息", f"{p}通信管理局")
        add(f"{p}通管局 App", f"{p}通信管理局")

    # 5) 法院：最高法
    for t in COURT_TERMS:
        add(f"最高人民法院 {t}", "最高人民法院")
    # 5) 法院：重点省市高院
    for p in ["北京", "上海", "广东", "浙江", "江苏", "四川", "山东", "湖北", "福建", "深圳", "杭州"]:
        add(f"{p}高院 数据", f"{p}高级人民法院")
        add(f"{p}法院 个人信息", f"{p}人民法院")

    # 6) 检察：最高检
    for t in PROC_TERMS:
        add(f"最高人民检察院 {t}", "最高人民检察院")
    # 6) 检察：重点省市检
    for p in ["北京", "上海", "广东", "浙江", "江苏", "四川", "山东", "湖北", "福建", "深圳"]:
        add(f"{p}检察 个人信息", f"{p}人民检察院")
        add(f"{p}检察院 公益诉讼", f"{p}人民检察院")

    # 7) 发改
    for t in NDRC_TERMS:
        add(f"国家发改委 {t}", "国家发展改革委")
    for p in ["北京", "上海", "广东", "浙江", "江苏", "四川", "山东"]:
        add(f"{p}发改 平台经济", f"{p}发展改革委")

