def authority_tier(name):
    """按公众号账号名判定档位（国家 + 省市多级机关都认）。

    返回 "wechat-official" / "academic" / "research" / None（None=不在放行名单）。
    """
    a = (name or "").strip()
    if not a:
        return None
    for tier, rx in ACCOUNT_TIER_RULES:
        if rx.search(a):
            return tier
    return None


