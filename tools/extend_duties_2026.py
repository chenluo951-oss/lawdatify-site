def main():
    d = json.load(open(P, encoding="utf-8"))
    cats = {c["id"]: c for c in d["categories"]}
    added_s = added_d = 0
    for cid, scenes in NEW.items():
        c = cats.get(cid)
        if not c:
            print(f"  ! 未找到主题大类 {cid}")
            continue
        have = {s["name"] for s in c["scenes"]}
        for name, duties, desc in scenes:
            if name in have:
                print(f"  · {cid}/{name} 已存在，跳过")
                continue
            c["scenes"].append({"name": name, "duties": duties})
            added_s += 1
            added_d += len(duties)
            print(f"  + {cid} / {name}（{len(duties)} 项）")
    tot_s = sum(len(c["scenes"]) for c in d["categories"])
    tot_d = sum(len(s["duties"]) for c in d["categories"] for s in c["scenes"])
    d["_meta"]["updated"] = date.today().isoformat()
    d["_meta"]["note"] = (d["_meta"].get("note", "") +
                          f"；{date.today()} 定向补写应用分发、备案变更注销、AI 应用登记、"
                          "合规审计、平台违规处置、安全事件报告、数据出境路径、补贴促销、"
                          "食品标识过渡期、即时零售平台化经营等场景。")
    json.dump(d, open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"✓ 新增场景 {added_s} 个 / 义务 {added_d} 项　"
          f"现有 {len(d['categories'])} 类 / {tot_s} 场景 / {tot_d} 项")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
